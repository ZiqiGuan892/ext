#!/usr/bin/env bash
# Source in each launcher before Python imports. No copying or installation.
huanyu_select_native_source() {
    local root="${HUANYU_VLLM_SOURCE:-${HUANYU_VLLM_OMNI_ROOT:-/opt/huawei/dataset/infra_data/code/vllm-omni-xy-dbb-dev}}"
    local entry retained="" required
    local -a entries=()
    if [[ "$root" != /* || "$root" == *:* || "$root" == *$'\n'* ]]; then
        echo 'FATAL: HUANYU_VLLM_SOURCE must be an absolute directory without colons/newlines' >&2
        return 2
    fi
    for required in vllm_omni/__init__.py \
        vllm_omni/model_executor/models/minicpmo_5_0/huanyu_audio.py \
        vllm_omni/model_executor/models/minicpmo_5_0/minicpmo_5_0_omni_llm.py; do
        [[ -r "$root/$required" ]] || {
            echo "FATAL: Huanyu-enabled source is incomplete: $root/$required" >&2
            return 1
        }
    done
    root="$(cd -- "$root" && pwd -P)" || return $?
    IFS=: read -r -a entries <<< "${PYTHONPATH:-}"
    for entry in "${entries[@]}"; do
        case "${entry%/}" in
            ""|"$root"|"${HUANYU_VLLM_SOURCE:-$root}"|"${HUANYU_VLLM_OMNI_ROOT:-$root}"|\
            /vllm-workspace/vllm-omni|/vllm-workspace/vllm-omni/*) continue ;;
        esac
        retained+="${retained:+:}$entry"
    done
    export HUANYU_VLLM_SOURCE="$root" HUANYU_VLLM_OMNI_ROOT="$root"
    export PYTHONPATH="$root${retained:+:$retained}"
}

if [[ "${BASH_SOURCE[0]}" == "$0" && "${1:-}" == --persist ]]; then
    set -euo pipefail
    huanyu_select_native_source
    profile="${HOME:?}/.huanyu-vllm-source.sh"
    hook='if [[ -r "$HOME/.huanyu-vllm-source.sh" ]]; then source "$HOME/.huanyu-vllm-source.sh"; fi'
    umask 077
    # Append under a shared-home lock, preserving existing contents, mode and symlinks.
    exec 8>>"$HOME/.bashrc"
    flock -x 8
    tmp=$(mktemp -- "$profile.XXXXXX")
    trap 'rm -f -- "$tmp"' EXIT
    {
        # Keep the startup hook self-contained even if the project checkout moves.
        printf '# Generated by native_source.sh --persist\n'
        declare -f huanyu_select_native_source
        printf 'if [[ -r %q ]]; then\n' "$HUANYU_VLLM_SOURCE/vllm_omni/__init__.py"
        printf '    export HUANYU_VLLM_SOURCE=%q\n    huanyu_select_native_source\nfi\n' "$HUANYU_VLLM_SOURCE"
    } > "$tmp"
    mv -fT -- "$tmp" "$profile"
    if ! grep -Fxq -- "$hook" "$HOME/.bashrc"; then
        printf '\n%s\n' "$hook" >&8
    fi
    printf '[huanyu-env] persisted vLLM-Omni source=%s via %s/.bashrc\n' "$HUANYU_VLLM_SOURCE" "$HOME"
else
    huanyu_select_native_source
fi
